#ifndef __ppmap_interface__
#define __ppmap_interface__

//==============================================================================
// Публичный интерфейс для работы с map (красно-чёрное дерево)
//==============================================================================

//------------------------------------------------------------------------------
// Начальная инициализация map.
void ppMap_init(ppMap* m, int (*cmp)(const void*, const void*));

//------------------------------------------------------------------------------
// Очистка всего map (освобождение всей выделенной памяти).
void ppMap_clear(ppMap* m);

//------------------------------------------------------------------------------
// Возвращает текущее количество элементов в map.
uint32_t ppMap_size(ppMap* m);

//------------------------------------------------------------------------------
// Проверяет, пуст ли map.
_Bool ppMap_empty(ppMap* m);

//------------------------------------------------------------------------------
// Вставка пары (ключ, значение) в map
// Если ключ уже существует, значение заменяется
void ppMap_insert(ppMap* m);

//------------------------------------------------------------------------------
// Поиск элемента по ключу.
// Возвращает 1, если ключ найден, иначе 0.
_Bool ppMap_find(ppMap* m);

// Получение значения по ключу с проверкой существования (при отсутствии – аварийное завершение)
void ppMap_at(ppMap* map);

//------------------------------------------------------------------------------
// Удаление элемента по ключу.
// Возвращает 1, если элемент был удалён, иначе 0 (ключ не найден).
_Bool ppMap_erase(ppMap* m);

//------------------------------------------------------------------------------
// Обход дерева в порядке возрастания ключей.
// Для каждого узла вызывается callback(key, value).
void ppMap_traverse(ppMap* m, void (*callback)(void* key, void* value));

//------------------------------------------------------------------------------
// Обход дерева с пользовательскими данными.
// Для каждого узла вызывается callback(key, value, user_data).
void ppMap_traverse_with_data(ppMap* m, void (*callback)(void* key, void* value, void* user_data), void* user_data);

//------------------------------------------------------------------------------
// Проверка на равенство двух map.
// Сравниваются размеры и содержимое (ключи и значения).
// Возвращает 1, если map полностью равны, иначе 0.
_Bool ppMap_is_equal(ppMap* m1, ppMap* m2);

//------------------------------------------------------------------------------
// Обмен содержимым между двумя map (быстро, обмениваются только указатели и счётчики).
void ppMap_swap(ppMap* a, ppMap* b);

//------------------------------------------------------------------------------
// Перемещение данных из src в dest. После операции dest содержит данные src,
// src становится пустым (но инициализированным).
void ppMap_move(ppMap* dest, ppMap* src);

//------------------------------------------------------------------------------
// Глубокое копирование данных из src в dest. Предыдущее содержимое dest удаляется.
void ppMap_copy(ppMap* dest, ppMap* src);

//------------------------------------------------------------------------------
// Проверка наличия ключа в map (без возврата значения).
// Возвращает 1, если ключ присутствует, иначе 0.
_Bool ppMap_contains(ppMap* m);

#endif // __ppmap_interface__